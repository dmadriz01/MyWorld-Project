package core;

public class Room {

    public int roomWidth;
    public int roomHeight;
    public int centersW;
    public int centersH;

    public Room(int roomWidth, int roomHeight, int centersW, int centersH){
        this.roomWidth = roomWidth;
        this.roomHeight = roomHeight;
        this.centersW = centersW;
        this.centersH = centersH;
    }

}
