package core;

public class Lights {
    private int x;        // bottom left corner x
    private int y;        // bottom left cornet y

    // Constructor
    public Lights(int x, int y) {
        this.x = x;
        this.y = y;

    }

    // Getters and setters for the attributes
    public int getX() {
        return x;
    }


    public int getY() {
        return y;
    }


}
